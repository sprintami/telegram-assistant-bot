export async function seedKnowledgeIfEmpty(workspaceId: string): Promise<void> {
  const existing = await prisma.record.count({ where: { workspaceId, module: "knowledge" } });
  if (existing > 0) return;

  await prisma.record.createMany({
    data: SEED_RECORDS.map((r, i) => ({
      id: randomUUID(),
      workspaceId,
      module: "knowledge",
      data: { title: r.title, category: r.category, body: r.body, createdAt: Date.now() - i },
    })),
  });
}
